import { create } from 'zustand'
import { persist } from 'zustand/middleware'

export type Lang = 'en' | 'zh'
export const IDX: Record<Lang, number> = { en: 0, zh: 1 }

interface LangState {
  lang: Lang
  setLang: (l: Lang) => void
}

export const useLang = create<LangState>()(
  persist((set) => ({ lang: 'en', setLang: (lang) => set({ lang }) }), {
    name: 'aegis-lang',
    // heal stores persisted before a language was dropped (e.g. 'es')
    merge: (persisted, current) => {
      const p = persisted as Partial<LangState> | undefined
      return { ...current, lang: p?.lang && p.lang in IDX ? p.lang : 'en' }
    },
  }),
)

